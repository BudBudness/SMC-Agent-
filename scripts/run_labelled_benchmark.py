#!/usr/bin/env python3
"""Run a multi-episode EURUSD intelligence benchmark.

Reference labels are generated by a deliberately separate, transparent OHLC
annotator. They are independent benchmark labels, not human ground truth.
Event scoring is timestamp-aligned to the same terminal 15M bar used by the
research engine so episode-wide observations are not counted as false
positives against a single-bar reference label.
"""
import argparse,json,os
import numpy as np
import pandas as pd
from smc_agent.providers import HistDataProvider
from smc_agent.dataset_validation import validate_ohlc
from smc_agent.engine import analyze
from smc_agent.benchmark import score_detection,score_sequence,aggregate_detection
from smc_agent.analogue import find_analogues,conditional_stats

EVENTS=("sweep","displacement","choch","bos","fvg")


def reference_labels(df):
    """Independently label events on the terminal 15M bar."""
    c,h,l,o=df.close,df.high,df.low,df.open
    labels=[]
    if len(df)>=21:
        ph,pl=float(h.iloc[-21:-1].max()),float(l.iloc[-21:-1].min())
        lh,ll,lc=float(h.iloc[-1]),float(l.iloc[-1]),float(c.iloc[-1])
        if (lh>ph and lc<ph) or (ll<pl and lc>pl): labels.append("sweep")
        rng=(h-l).rolling(20).median().iloc[-1]
        if pd.notna(rng) and rng>0 and abs(lc-float(o.iloc[-1]))/rng>=1.5: labels.append("displacement")
        if lc>ph: labels.append("bos")
        if lc<pl: labels.append("choch")
    if len(df)>=4:
        a,b,z=df.iloc[-3],df.iloc[-2],df.iloc[-1]
        if float(a.high)<float(z.low) or float(a.low)>float(z.high): labels.append("fvg")
    return list(dict.fromkeys(labels))


def _terminal_15m(df):
    bars=df.resample("15min").agg(
        {"open":"first","high":"max","low":"min","close":"last"}
    ).dropna()
    return bars


def engine_labels(report, start, end):
    observed=[]
    for e in report.as_dict().get("events",[]):
        name=e.get("name")
        if name not in EVENTS or not e.get("time"):
            continue
        ts=pd.Timestamp(e["time"])
        if start <= ts <= end:
            observed.append(name)
    return list(dict.fromkeys(observed))


def episode_record(df,i):
    bars=_terminal_15m(df)
    terminal=bars.iloc[-1:]
    terminal_start=terminal.index[-1]
    terminal_end=df.index[-1]
    ref=reference_labels(bars)
    report=analyze(df,symbol="EURUSD",now=terminal_end)
    obs=engine_labels(report,terminal_start,terminal_end)
    state=report.market_state
    return {
        "episode":i,
        "start":df.index[0].isoformat(),
        "end":df.index[-1].isoformat(),
        "benchmark_bar_start":terminal_start.isoformat(),
        "benchmark_bar_end":terminal_end.isoformat(),
        "reference_events":ref,
        "observed_events":obs,
        "detection":score_detection(ref,obs),
        "sequence":score_sequence(ref,obs),
        "weekly_bias":state.get("weekly_bias"),
        "regime":state.get("timeframes",{}).get("12M"),
        "daily_location":state.get("daily_location"),
        "amd":state.get("4H_AMD",{}).get("phase"),
        "displacement":state.get("displacement"),
        "outcome_20m":float(df.close.iloc[-1]/df.close.iloc[-21]-1) if len(df)>=21 else None,
    }


def main():
    p=argparse.ArgumentParser()
    p.add_argument("csv")
    p.add_argument("--episodes",type=int,default=20)
    p.add_argument("--out",default="benchmark-results/labelled-eurusd.json")
    a=p.parse_args()
    df=HistDataProvider(a.csv).candles()
    v=validate_ohlc(df)
    if not v["valid"]: raise SystemExit(json.dumps(v))
    n=max(1,len(df)//a.episodes)
    rows=[]
    for i in range(a.episodes):
        s=i*n; e=(i+1)*n if i<a.episodes-1 else len(df)
        ep=df.iloc[s:e]
        if len(ep)>=100: rows.append(episode_record(ep,i+1))

    history=[]; analogue=[]
    for x in rows:
        pattern={
            "regime":x["regime"],
            "weekly_bias":x["weekly_bias"],
            "location":x["daily_location"],
            "sweep":"sweep" in x["reference_events"],
            "displacement":x["displacement"],
            "choch":"choch" in x["reference_events"],
            "bos":"bos" in x["reference_events"],
            "amd":x["amd"],
        }
        matches=find_analogues(history,pattern,limit=5,min_similarity=.35)
        analogue.append({
            "episode":x["episode"],
            "matches":len(matches),
            "conditional_stats":conditional_stats(matches,"outcome") if matches else {"samples":0},
        })
        history.append({**pattern,"outcome":x["outcome_20m"]})

    seq=[x["sequence"]["order_accuracy"] for x in rows if x["sequence"]["order_pairs"]]
    result={
        "symbol":"EURUSD",
        "method":"independent_rule_based_reference_labels",
        "label_status":"benchmark_labels_not_human_ground_truth",
        "event_alignment":"terminal_15m_bar",
        "episodes":len(rows),
        "dataset_validation":v,
        "start":df.index[0].isoformat(),
        "end":df.index[-1].isoformat(),
        "detection":aggregate_detection([x["detection"] for x in rows]),
        "sequence":{"episodes_with_order_pairs":len(seq),"mean_order_accuracy":float(np.mean(seq)) if seq else 0.0},
        "analogue":{"episodes":analogue},
        "episode_results":rows,
    }
    os.makedirs(os.path.dirname(a.out) or ".",exist_ok=True)
    with open(a.out,"w",encoding="utf-8") as f: json.dump(result,f,indent=2)
    print(json.dumps(result,indent=2))


if __name__=="__main__": main()
